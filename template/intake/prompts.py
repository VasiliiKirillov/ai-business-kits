"""Системные промпты собираются из конфига. Ничего бизнес-специфичного в коде нет."""
import json
from datetime import date

from .catalog import Catalog
from .config import Config
from .schema import build_lead_model

YO = "\u0451"  # буква, которую нельзя писать в файлах
WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]

TYPE_RULES = {
    "date": "приводи к YYYY-MM-DD (\"завтра\", \"с 20го\", \"в пятницу\" считай от сегодняшней даты)",
    "time": "время в формате HH:MM, 24 часа (\"в 3 дня\" = 15:00)",
    "int": "целое число",
    "phone": "телефон или мессенджер для связи, как написал клиент; номер документа это НЕ телефон; нет - null",
    "email": "адрес почты, как написал клиент",
    "item": "только если клиент сам назвал позицию каталога или категорию; приводи к названию из каталога (см. ниже)",
}


def parser_system(cfg: Config, catalog: Catalog, today: date) -> str:
    b, r = cfg.business, cfg.request
    schema = json.dumps(build_lead_model(cfg).model_json_schema()["properties"], ensure_ascii=False)
    L = [f'Ты разбираешь входящие обращения клиентов бизнеса "{b.name}"' + (f" ({b.description})." if b.description else "."),
         f"Сегодня {today.isoformat()}, {WEEKDAYS[today.weekday()]}.",
         "", "Верни ТОЛЬКО JSON без markdown по схеме:", schema, "",
         f'Тебе дают ВСЮ переписку по текущему обращению строками "Клиент: ...", "Бот: ...", "Менеджер: ...". '
         f"Верни полное ТЕКУЩЕЕ состояние ({r.noun}), собранное из всей переписки. Ответы клиента вроде \"да\" "
         "относятся к вопросу бота перед ними: если бот спросил \"на три дня?\" и клиент сказал \"да\", значит три дня.",
         "", "Правила:",
         f"- type определяй по ПЕРВОМУ сообщению клиента: request (хочет оформить {r.noun}), question (вопрос без конкретного "
         "заказа), complaint (претензия к сервису: не сделали, обманули, никто не отвечает), spam (реклама, мусор). "
         'Раздражение или мат в адрес бота ("ты че", "тупишь") - это НЕ жалоба и НЕ спам. '
         'Короткие реплики внутри диалога ("да", "ок", "не знаю") - не спам.',
         "- Поля, которых нигде в переписке нет, - null. Ничего не выдумывай."]
    for f in r.fields:
        rule = TYPE_RULES.get(f.type, "")
        if f.type == "choice":
            rule = "одно из: " + ", ".join(f.choices)
        L.append(f"- {f.key} ({f.label}): {f.describe}" + (f". {rule}" if rule else ""))
        if f.ask_only_if_unclear:
            L.append(f"  {f.key}_unclear=true, только если клиент назвал это неясно и значение нельзя определить "
                     f"(тогда {f.key}=null); если не сказано вообще или ясно - false.")
        if f.declinable:
            L.append(f"  declined_field=\"{f.key}\", только если клиент в ПОСЛЕДНЕМ сообщении отказался это давать "
                     '("не дам", "без этого", "пишите сюда"), иначе declined_field=null (отказ в прошлых сообщениях не считается).')
    ik = cfg.item_key
    if ik:
        L.append(f'- {ik}: если клиент назвал основной вариант и запасной ("A, а если нет, то B"), пиши "A (или B)": первый основной. '
                 "Если просто передумал и выбрал другой, пиши только новый. Если есть строка \"Менеджер: <X> нет в наличии\" "
                 f"или \"Менеджер: <X> занято\", это значение не подходит: поле = null, пока клиент не назвал другое после этой строки.")
    L += ['- confirmed: true, только если в начале есть пометка "[Бот показал клиенту итог]" и клиент в ПОСЛЕДНЕМ сообщении '
          "явно согласился с итогом (да, ок, верно, yes). Если он что-то меняет или спрашивает - false.",
          '- contact и name: клиент пишет из мессенджера, в строке "[Клиент пишет из мессенджера: ...]" его имя и @username. '
          "name - имя клиента, если он не назвал другое; contact - этот @username, если клиент не дал другой контакт.",
          "- wants_photo=true, только если клиент в ПОСЛЕДНЕМ сообщении просит фото позиции (\"скинь фотку\", \"как выглядит\", "
          "\"photo pls\"), иначе false. photo_of: позиция, фото которой он просит, если назвал. Если клиент просто просит фото, "
          "поля заказа из-за этого НЕ меняй."]
    idc = r.identity_document
    if idc.enabled:
        L.append(f"- doc_*: данные ({idc.name}): бери только то, что клиент написал сам или что есть в строке "
                 '"[прислал фото документа: ...]". Нет - null. Номер документа это НЕ телефон.')
    L += [f"- {h}" for h in r.parse_hints]
    if catalog.items:
        groups: dict = {}
        for it in catalog.items:
            groups.setdefault(it.category or "-", []).append(it.name + (f" ({', '.join(it.aliases)})" if it.aliases else ""))
        L += ["", "Каталог (название и синонимы клиента; в поле позиции пиши название из каталога, а если назвал только категорию - название категории):"]
        L += [f"- {c}: " + "; ".join(v) for c, v in groups.items()]
    if cfg.bot.style.replace_yo:
        L.append(f"- Никогда не пиши букву {YO}, только е.")
    return "\n".join(L)


def chat_system(cfg: Config, catalog: Catalog, today: date, status: str) -> str:
    b, bot = cfg.business, cfg.bot
    st = bot.style
    L = [f"Ты {bot.persona}" + (f", {b.description}" if b.description else "") + f". Пишешь клиенту в мессенджере. Сегодня {today.isoformat()}.", ""]
    if bot.tone:
        L.append(bot.tone.strip())
    if st.no_emoji or st.no_exclamation:
        L.append(" ".join(x for x in ("Никаких эмодзи." if st.no_emoji else "", "Без восклицательных знаков." if st.no_exclamation else "") if x))
    L.append({"auto": 'Обращайся на "ты", если клиент пишет неформально, иначе на "вы".',
              "ty": 'Обращайся к клиенту на "ты".', "vy": 'Обращайся к клиенту на "вы".'}[bot.address])
    if bot.banned_phrases:
        L.append("Не используй дежурные фразы: " + ", ".join(f'"{p}"' for p in bot.banned_phrases) + ". Не благодари и не извиняйся без повода.")
    L += ["",
          "Жесткие правила:",
          "- Отвечай на то, что спросили. Если клиент задал вопрос, сначала ответь на него, а потом, только если в статусе есть вопрос к клиенту, задай его.",
          "- Задавай не больше одного вопроса за раз и только если статус его требует.",
          "- Не пересказывай клиенту то, что он только что сказал сам. Исключение - итог перед подтверждением: покажи его списком без воды.",
          "- Никогда не описывай характеристики позиций, если клиент сам не спросил; и только то, что написано в разделе \"Что можно рассказать\".",
          "- Цены называй только из статуса или прайса ниже, никогда не выдумывай. Прошлые цены не комментируй.",
          "- Предлагая альтернативы, не спрашивай \"берете?\", \"подойдет?\": назови факт и цены, клиент ответит сам.",
          "- Никогда не упоминай внутреннюю кухню: заявку, номер заявки, поля, систему, статус, \"записано\". Единственное исключение - "
          "когда статус прямо говорит, что передано менеджеру: тогда коротко \"передал менеджеру\".",
          "- Не оценивай ответы клиента и не язви. Если ответ двусмысленный, коротко переспроси без оценок.",
          "- Язык ответа строго как в последнем сообщении клиента.",
          f"- {r_noun(cfg)} подтверждает менеджер: сам не подтверждай и ничего не обещай."]
    if st.replace_yo or st.plain_dashes:
        L.append("- " + " ".join(x for x in (f"Никогда не пиши букву {YO}, только е." if st.replace_yo else "",
                                              "Только короткий дефис, не длинное тире." if st.plain_dashes else "") if x))
    if bot.facts:
        L += ["", "Факты (только их и данные каталога, больше ничего не выдумывай):"] + [f"- {x}" for x in bot.facts]
    if catalog.items:
        L += ["", f"Прайс, одна точная цена на позицию (больше никаких цен не называй): {catalog.price_list()}."]
        det = [f"{i.name}: {i.details}" for i in catalog.items if i.details]
        if det:
            L += ["Что можно рассказать о позициях (только если клиент спросил):"] + [f"- {x}" for x in det]
    if bot.tone_examples:
        L += ["", "Примеры тона: " + ", ".join(f'"{x}"' for x in bot.tone_examples)]
    L += ["", 'В конце промпта стоит строка "[Статус: ...]". Ты не решаешь сам, что делать дальше: опирайся только на статус и говори '
          "ровно то, что в нем сказано. Не переспрашивай то, что клиент уже сказал, не обещай ничего сверх статуса. "
          "Выдай только текст сообщения клиенту.", f"[Статус: {status}]"]
    return "\n".join(L)


def r_noun(cfg: Config) -> str:
    n = cfg.request.noun
    return n[:1].upper() + n[1:]
