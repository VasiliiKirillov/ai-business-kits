"""Что ядро ждет от мессенджера. Новый канал (WhatsApp, VK, ...) = новый класс с этими методами."""
from typing import Protocol


class Messenger(Protocol):
    channel: str

    async def send_client(self, client_id: str, text: str) -> None: ...
    async def send_client_photo(self, client_id: str, path: str, caption: str) -> None: ...
    async def send_card(self, lead_id: int, text: str, buttons: list[str]) -> None: ...  # ["confirm","own"] | ["own"]
    async def notify_manager(self, text: str) -> None: ...
    async def send_manager_file(self, path: str, caption: str) -> None: ...
    async def forward_to_manager(self, client_id: str, message_ref: str, caption: str) -> None: ...
